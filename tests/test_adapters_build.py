@pytest.mark.ac("E12-AC-09")
def test_build_py_runs_as_a_script_in_an_installed_kit(tmp_path: Path) -> None:
    repo = git_repo(tmp_path / "repo")
    assert cli.main([str(repo)]) == 0
    result = subprocess.run(
        [sys.executable, str(repo / ".factory" / "adapters" / "build.py")],
        cwd=repo,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result


# --- AC-09: install.py runs the build -----------------------------------------------------------


@pytest.mark.ac("E12-AC-09")
def test_install_builds_the_tool_files(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    repo = git_repo(tmp_path / "repo")
    assert cli.main([str(repo)]) == 0
    manifest = json.loads((repo / MANIFEST).read_text(encoding="utf-8"))
    assert ".claude/agents/verifier.md" in manifest["files"]
    assert ".github/agents/verifier.agent.md" in manifest["files"]
    assert ".cursor/skills/handoff/SKILL.md" in manifest["files"]
    for path in manifest["files"]:
        assert (repo / path).is_file(), path
    capsys.readouterr()
    assert cli.main(["check", str(repo)]) == 0, capsys.readouterr()


@pytest.mark.ac("E12-AC-09")
def test_a_dry_run_builds_nothing(tmp_path: Path) -> None:
    repo = git_repo(tmp_path / "repo")
    assert cli.main([str(repo), "--dry-run"]) == 0
    assert not (repo / ".claude").exists()
    assert not (repo / MANIFEST).exists()


