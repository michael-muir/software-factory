# --- AC-02: skills, byte for byte ---------------------------------------------------------------


@pytest.mark.ac("E12-AC-02")
@pytest.mark.parametrize("tool_dir", [".claude/skills", ".github/skills", ".cursor/skills"])
def test_every_skill_file_is_copied_unchanged(tmp_path: Path, tool_dir: str) -> None:
    root = repo_with(tmp_path, [])
    extra = root / ".factory" / "skills" / "release" / "scripts" / "bump.py"
    extra.parent.mkdir(parents=True)
    extra.write_bytes(b"print('bump')\n")
    out = build.build(root)
    source = root / ".factory" / "skills"
    expected = {
        f"{tool_dir}/{p.relative_to(source).as_posix()}": p.read_bytes()
        for p in source.rglob("*")
        if p.is_file()
    }
    got = {p: b for p, b in out.items() if p.startswith(f"{tool_dir}/")}
    assert got == expected


