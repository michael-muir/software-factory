KIT = REPO_ROOT / "kit" / ".factory"
CORE = KIT / "agents" / "core"
SKILLS = KIT / "skills"
MANIFEST = ".factory/adapters/generated.json"
NOTICE = "<!-- Generated by .factory/adapters/build.py from "

CLAUDE = {
    "read": ["Read"],
    "search": ["Glob", "Grep"],
    "edit": ["Edit", "MultiEdit", "NotebookEdit"],
    "write": ["Write"],
    "run": ["Bash", "PowerShell"],
    "web": ["WebFetch", "WebSearch"],
}
COPILOT = {
    "read": "read",
    "search": "search",
    "edit": "edit",
    "write": "edit",
    "run": "execute",
    "web": "web",
}


def repo_with(
    tmp_path: Path, roles: list[str] | None = None, tools: list[str] | None = None
) -> Path:
    """A repo with the kit's core roles (or some of them) and all its skills."""
    root = tmp_path / "repo"
    core = root / ".factory" / "agents" / "core"
    core.mkdir(parents=True)
    for path in CORE.glob("*.md"):
        if roles is None or path.stem in roles:
            shutil.copyfile(path, core / path.name)
    shutil.copytree(SKILLS, root / ".factory" / "skills")
    if tools is not None:
        (root / ".agentic").mkdir(parents=True, exist_ok=True)
        (root / ".agentic" / "config.toml").write_text(
            f"[adapters]\ntools = {json.dumps(tools)}\n", encoding="utf-8"
        )
    return root


def front(text: str) -> tuple[dict[str, object], str]:
    """Front matter whose values are JSON literals (design note), and the rest of the file.

    One blank line follows the front matter, as Prettier writes it, so the files pass a
    repo's Markdown format check.
    """
    lines = text.split("\n")
    assert lines[0] == "---", lines[0]
    end = lines.index("---", 1)
    data: dict[str, object] = {}
    for line in lines[1:end]:
        key, _, value = line.partition(": ")
        assert key not in data, f"{key} twice"
        data[key] = json.loads(value)
    assert lines[end + 1] == "", "one blank line after the front matter"
    return data, "\n".join(lines[end + 2 :])


def card(name: str) -> tuple[dict[str, object], str]:
    parsed = state.parse((CORE / f"{name}.md").read_text(encoding="utf-8"))
    assert not isinstance(parsed, str)
    return parsed


def neutral_tools(name: str) -> list[str]:
    tools = card(name)[0]["tools"]
    assert isinstance(tools, list)
    return [str(t) for t in tools]


ROLES = sorted(p.stem for p in CORE.glob("*.md"))


# --- AC-01: agent files for three tools ---------------------------------------------------------


@pytest.mark.ac("E12-AC-01")
@pytest.mark.parametrize("name", ROLES)
def test_the_claude_code_agent(tmp_path: Path, name: str) -> None:
    out = build.build(repo_with(tmp_path))
    data, rest = front(out[f".claude/agents/{name}.md"].decode())
    assert list(data) == ["name", "description", "tools"]
    assert data["name"] == name
    assert data["description"] == card(name)[0]["summary"]
    expected = [t for tool in neutral_tools(name) for t in CLAUDE[tool]]
    assert data["tools"] == ", ".join(expected)
    assert rest.startswith(f"{NOTICE}.factory/agents/core/{name}.md.")


@pytest.mark.ac("E12-AC-01")
@pytest.mark.parametrize("name", ROLES)
def test_the_copilot_agent(tmp_path: Path, name: str) -> None:
    out = build.build(repo_with(tmp_path))
    data, rest = front(out[f".github/agents/{name}.agent.md"].decode())
    assert list(data) == ["name", "description", "tools"]
    assert (data["name"], data["description"]) == (name, card(name)[0]["summary"])
    expected = list(dict.fromkeys(COPILOT[t] for t in neutral_tools(name)))
    assert data["tools"] == expected
    assert rest.startswith(NOTICE)


@pytest.mark.ac("E12-AC-01")
@pytest.mark.parametrize("name", ROLES)
def test_the_cursor_agent(tmp_path: Path, name: str) -> None:
    out = build.build(repo_with(tmp_path))
    data, rest = front(out[f".cursor/agents/{name}.md"].decode())
    assert list(data) == ["name", "description"]
    assert (data["name"], data["description"]) == (name, card(name)[0]["summary"])
