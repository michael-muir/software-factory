@pytest.mark.ac("E12-AC-01")
@pytest.mark.parametrize("tool_dir", [".claude/agents", ".github/agents", ".cursor/agents"])
def test_each_agent_carries_the_role_cards_body(tmp_path: Path, tool_dir: str) -> None:
    out = build.build(repo_with(tmp_path, ["verifier"]))
    path = next(p for p in out if p.startswith(f"{tool_dir}/verifier"))
    _, rest = front(out[path].decode())
    notice, _, body = rest.partition("\n")
    assert notice.startswith(NOTICE)
    assert body == card("verifier")[1]


@pytest.mark.ac("E12-AC-01")
def test_a_repos_own_roles_are_compiled_too_but_not_underscore_files(tmp_path: Path) -> None:
    root = repo_with(tmp_path, ["verifier"])
    own = (CORE / "retro.md").read_text(encoding="utf-8").replace('"retro"', '"house-style"', 1)
    (root / ".factory" / "agents" / "house-style.md").write_text(own, encoding="utf-8")
    (root / ".factory" / "agents" / "_notes.md").write_text("notes\n", encoding="utf-8")
    out = build.build(root)
    agents_out = sorted(p for p in out if p.startswith(".claude/agents/"))
    assert agents_out == [".claude/agents/house-style.md", ".claude/agents/verifier.md"]


