# --- writing, the manifest and removal (ADR 0023) -----------------------------------------------


def run_build(root: Path, *args: str) -> int:
    return build.main(["--root", str(root), *args])


@pytest.mark.ac("E12-AC-09")
def test_the_build_writes_its_files_and_a_manifest(tmp_path: Path) -> None:
    root = repo_with(tmp_path, ["verifier", "retro"])
    assert run_build(root) == 0
    expected = build.build(root)
    for path, data in expected.items():
        assert (root / path).read_bytes() == data, path
    manifest = json.loads((root / MANIFEST).read_text(encoding="utf-8"))
    assert sorted(manifest["files"]) == sorted(expected)
    assert list(manifest["files"]) == sorted(manifest["files"])


@pytest.mark.ac("E12-AC-09")
def test_a_deleted_role_loses_its_files_and_foreign_files_stay(tmp_path: Path) -> None:
    root = repo_with(tmp_path, ["verifier", "retro"])
    assert run_build(root) == 0
    mine = root / ".claude" / "agents" / "my-own.md"
    mine.write_text("hand written\n", encoding="utf-8")
    (root / ".factory" / "agents" / "core" / "retro.md").unlink()
    assert run_build(root) == 0
    for path in (
        ".claude/agents/retro.md",
        ".github/agents/retro.agent.md",
        ".cursor/agents/retro.md",
    ):
        assert not (root / path).exists(), path
    assert (root / ".claude" / "agents" / "verifier.md").exists()
    assert mine.read_text(encoding="utf-8") == "hand written\n"


@pytest.mark.ac("E12-AC-09")
@pytest.mark.parametrize(
    ("tools", "present", "absent"),
    [
        (["claude-code"], ".claude", (".github", ".cursor")),
        (["copilot"], ".github", (".claude", ".cursor")),
        (["cursor"], ".cursor", (".claude", ".github")),
    ],
)
def test_the_config_picks_the_tools(
    tmp_path: Path, tools: list[str], present: str, absent: tuple[str, ...]
) -> None:
    out = build.build(repo_with(tmp_path, ["verifier"], tools))
    assert any(p.startswith(present + "/") for p in out)
    for other in absent:
        assert not any(p.startswith(other + "/") for p in out), other


@pytest.mark.ac("E12-AC-09")
def test_all_three_tools_by_default(tmp_path: Path) -> None:
    out = build.build(repo_with(tmp_path, ["verifier"]))
    for top in (".claude", ".github", ".cursor"):
        assert any(p.startswith(top + "/") for p in out), top
    assert config_schema.default_for("adapters.tools") == ["claude-code", "copilot", "cursor"]


@pytest.mark.ac("E12-AC-09")
def test_dropping_a_tool_removes_its_files(tmp_path: Path) -> None:
    root = repo_with(tmp_path, ["verifier"])
    assert run_build(root) == 0
    (root / ".agentic").mkdir(exist_ok=True)
    (root / ".agentic" / "config.toml").write_text(
        '[adapters]\ntools = ["claude-code", "copilot"]\n', encoding="utf-8"
    )
    assert run_build(root) == 0
    assert not any(p.is_file() for p in (root / ".cursor").rglob("*"))
    assert (root / ".claude" / "agents" / "verifier.md").exists()


