"""Software Factory tool adapters (E12, ADR 0023). Standard library only.

    python .factory/adapters/build.py [--check] [--root PATH]

Compiles the neutral roles (`.factory/agents/**`) and skills (`.factory/skills/*/`) into the
files Claude Code, GitHub Copilot and Cursor read, and registers each tool's hook (ADR 0024),
for the tools in `.agentic/config.toml` `[adapters] tools` (default: all three). The output is
committed. `.factory/adapters/generated.json` lists what was written, so a later build removes
exactly the files it no longer produces and never a repo's own files beside them. The factory's
hook entry is merged into a repo's own `.claude/settings.json` and `.cursor/hooks.json`, and only
that entry is taken out when a tool is dropped. `--check` builds in memory, writes nothing, and
names each file that's missing, stale or no longer produced (exit 1), so the gate and
`install.py check` can fail on drift.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import os
import sys
import tempfile
import tomllib
from collections.abc import Iterable, Sequence
from pathlib import Path
from types import ModuleType
from typing import Any

AGENTS_PATH = Path(__file__).resolve().parent.parent / "agents" / "agents.py"
MANIFEST_REL = ".factory/adapters/generated.json"
CONFIG_REL = ".agentic/config.toml"
TOOLS = ("claude-code", "copilot", "cursor")
TOOL_DIRS = {"claude-code": ".claude", "copilot": ".github", "cursor": ".cursor"}
NOTICE = (
    "<!-- Generated by .factory/adapters/build.py from {source}. "
    "Edit the source, then run build.py. -->"
)

CLAUDE_SETTINGS_REL = ".claude/settings.json"
COPILOT_HOOKS_REL = ".github/hooks/factory.json"
CURSOR_HOOKS_REL = ".cursor/hooks.json"


def hook_command(launcher: str) -> str:
    """A hook command that runs the sh `launcher` alike from sh, bash, PowerShell 5.1 and pwsh.

    The commands in `.claude/settings.json` and `.cursor/hooks.json` are shared by shells: Claude
    Code runs them with sh or Git Bash, Cursor on Windows with PowerShell, and Copilot CLI, which
    reads `.claude/settings.json` too, with PowerShell on Windows and without $CLAUDE_PROJECT_DIR.
    So the command needs no sh on PATH and no variable: git runs a `!` alias with its own sh
    (Git for Windows brings one), from the top of the repo it is started in, with stdin passed
    through. The single quotes are literal in every one of those shells, and there's no double
    quote for PowerShell 5.1 to mangle on its way to git. `exit $LASTEXITCODE` keeps the exit
    code 2 that blocks a call, which PowerShell would turn into 1; sh reads it as a bare `exit`,
    which keeps git's.
    """
    alias = f"alias.factory-hook=!sh .factory/agents/{launcher}"
    return f"git -c '{alias}' factory-hook; exit $LASTEXITCODE"


COPILOT_ENTRY = {
    "type": "command",
    "bash": "sh .factory/agents/copilot-hook",  # the only form Copilot's cloud agent runs
    "powershell": hook_command("copilot-hook"),
    "timeoutSec": 10,
}
CURSOR_ENTRY = {"command": hook_command("cursor-hook"), "timeout": 10, "failClosed": True}
# Configs shared with a repo's own settings: {path: (hook event, the launcher that marks ours)}
SHARED = {
    CLAUDE_SETTINGS_REL: ("PreToolUse", "claude-hook"),
    CURSOR_HOOKS_REL: ("preToolUse", "cursor-hook"),
}


class BuildError(Exception):
    """The sources or the config can't be built: exit 2."""


def _load_agents() -> ModuleType:
    """The sibling agents module (ADR 0016 pattern), which brings state.py with it."""
    spec = importlib.util.spec_from_file_location("factory_agents", AGENTS_PATH)
    if spec is None or spec.loader is None or not AGENTS_PATH.is_file():
        raise BuildError(f"build.py needs {AGENTS_PATH.parent.name}/agents.py beside it")
    module = importlib.util.module_from_spec(spec)
    sys.modules["factory_agents"] = module
    spec.loader.exec_module(module)
    return module


def configured_tools(root: Path) -> tuple[str, ...]:
    """`[adapters] tools`, in the fixed order of TOOLS; all three when unset."""
    path = root / CONFIG_REL
    if not path.is_file():
        return TOOLS
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as exc:
        raise BuildError(f"{CONFIG_REL}: invalid TOML: {exc}") from None
    chosen = data.get("adapters", {}).get("tools", list(TOOLS))
    if not isinstance(chosen, list) or any(tool not in TOOLS for tool in chosen):
        raise BuildError(f"{CONFIG_REL}: adapters.tools must list only {', '.join(TOOLS)}")
    return tuple(tool for tool in TOOLS if tool in chosen)


def _front(fields: Iterable[tuple[str, object]]) -> str:
    """YAML front matter whose values are JSON literals: valid YAML, read back exactly."""
    lines = [f"{key}: {json.dumps(value, ensure_ascii=False)}" for key, value in fields]
    return "---\n" + "\n".join(lines) + "\n---\n"


def _agent_file(card: Any, fields: list[tuple[str, object]]) -> bytes:
    # The blank line after the front matter is Prettier's layout, so a repo's format check passes.
    text = _front(fields) + "\n" + NOTICE.format(source=card.source) + "\n" + str(card.body)
    return text.encode("utf-8")


def _agents(agents: ModuleType, card: Any, tools: tuple[str, ...]) -> dict[str, bytes]:
    out: dict[str, bytes] = {}
    base = [("name", card.name), ("description", card.summary)]
    if "claude-code" in tools:
        names = [n for tool in card.tools for n in agents.CLAUDE_CODE_AGENT_TOOLS[tool]]
        fields = [*base, ("tools", ", ".join(names))]
        out[f".claude/agents/{card.name}.md"] = _agent_file(card, fields)
    if "copilot" in tools:
        aliases = list(dict.fromkeys(agents.COPILOT_AGENT_TOOLS[tool] for tool in card.tools))
        fields = [*base, ("tools", aliases)]
        out[f".github/agents/{card.name}.agent.md"] = _agent_file(card, fields)
    if "cursor" in tools:
        out[f".cursor/agents/{card.name}.md"] = _agent_file(card, base)
    return out


def _skills(agents: ModuleType, root: Path, tools: tuple[str, ...]) -> dict[str, bytes]:
    source = root / agents.SKILLS_REL
    files = sorted(p for p in source.rglob("*") if p.is_file()) if source.is_dir() else []
    out: dict[str, bytes] = {}
    for path in files:
        rel = path.relative_to(source).as_posix()
        for tool in tools:
            out[f"{TOOL_DIRS[tool]}/skills/{rel}"] = path.read_bytes()
    return out


def _json(data: object) -> bytes:
    return (json.dumps(data, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def _claude_entry(agents: ModuleType) -> dict[str, object]:
    """E03's PreToolUse entry (ADR 0017): every mapped tool, blocking on failure."""
    command = hook_command("claude-hook")
    return {
        "matcher": "|".join(agents.CLAUDE_CODE_TOOLS),
        "hooks": [{"type": "command", "command": command, "timeout": 10, "onFailure": "block"}],
    }


def _load_json(root: Path, rel: str) -> dict[str, Any]:
    path = root / rel
    if not path.is_file():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise BuildError(f"{rel}: can't read it as JSON: {exc}") from None
    if not isinstance(data, dict):
        raise BuildError(f"{rel}: must hold a JSON object")
    return data


def _ours(entry: object, launcher: str) -> bool:
    """Does a hook entry run the factory's launcher, at the top level or in its `hooks`?"""
    if not isinstance(entry, dict):
        return False
    inner = entry.get("hooks")
    commands = [entry.get("command")]
    if isinstance(inner, list):
        commands += [h.get("command") for h in inner if isinstance(h, dict)]
    return any(isinstance(c, str) and f".factory/agents/{launcher}" in c for c in commands)


def _merged(data: dict[str, Any], rel: str, entry: object | None) -> dict[str, Any]:
    """`data` with the factory's entry in place of the old one (else last), or taken out."""
    event, launcher = SHARED[rel]
    hooks = data.get("hooks", {})
    entries = hooks.get(event, []) if isinstance(hooks, dict) else None
    if not isinstance(entries, list):
        raise BuildError(f"{rel}: hooks.{event} must be a list in an object")
    kept: list[object] = []
    placed = entry is None
    for old in entries:
        if not _ours(old, launcher):
            kept.append(old)
        elif not placed:
            kept.append(entry)
            placed = True
    if not placed:
        kept.append(entry)
    hooks = dict(hooks)
    if kept:
        hooks[event] = kept
    else:
        hooks.pop(event, None)
    result = dict(data)
    if hooks:
        result["hooks"] = hooks
    else:
        result.pop("hooks", None)
    return result


def _hooks(agents: ModuleType, root: Path, tools: tuple[str, ...]) -> dict[str, bytes]:
    out: dict[str, bytes] = {}
    if "claude-code" in tools:
        data = _load_json(root, CLAUDE_SETTINGS_REL)
        merged = _merged(data, CLAUDE_SETTINGS_REL, _claude_entry(agents))
        out[CLAUDE_SETTINGS_REL] = _json(merged)
    if "copilot" in tools:
        out[COPILOT_HOOKS_REL] = _json({"version": 1, "hooks": {"preToolUse": [COPILOT_ENTRY]}})
    if "cursor" in tools:
        data = _load_json(root, CURSOR_HOOKS_REL)
        data = data if "version" in data else {"version": 1, **data}
        out[CURSOR_HOOKS_REL] = _json(_merged(data, CURSOR_HOOKS_REL, CURSOR_ENTRY))
    return out


def build(root: Path) -> dict[str, bytes]:
    """Every generated file as {repo-relative path: bytes}, sorted by path. Writes nothing."""
    agents = _load_agents()
    tools = configured_tools(root)
    try:
        cards = agents.role_cards(root)
    except agents.Unusable as exc:
        raise BuildError(str(exc)) from None
    out: dict[str, bytes] = {}
    for card in cards:
        out.update(_agents(agents, card, tools))
    out.update(_skills(agents, root, tools))
    out.update(_hooks(agents, root, tools))
    return dict(sorted(out.items()))


def _manifest(root: Path) -> dict[str, str]:
    path = root / MANIFEST_REL
    if not path.is_file():
        return {}
    files = json.loads(path.read_text(encoding="utf-8")).get("files", {})
    return {str(k): str(v) for k, v in files.items()} if isinstance(files, dict) else {}


def _write_bytes(path: Path, data: bytes) -> None:
    """Atomic: a temp file in the same folder, then a rename."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def _prune(root: Path, path: Path) -> None:
    """Remove folders the build emptied, up to the tool's top folder."""
    tops = {root / top for top in TOOL_DIRS.values()}
    folder = path.parent
    while folder not in tops and folder != root and folder.is_dir() and not any(folder.iterdir()):
        folder.rmdir()
        folder = folder.parent


def _manifest_bytes(agents: ModuleType, out: dict[str, bytes]) -> bytes:
    manifest = {"files": {rel: agents.lf_sha256(data) for rel, data in out.items()}}
    return (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def check(root: Path) -> tuple[int, list[str]]:
    """(files produced, drift lines): `<path>: missing|stale|extra`. Writes nothing.

    Content is compared with CRLF read as LF, as the manifest's hashes are, so a Windows
    checkout of a current file isn't stale. `extra` is a file the last build recorded that the
    sources no longer produce. The manifest itself is checked like any generated file.
    """
    agents = _load_agents()
    out = build(root)
    expected = {**out, MANIFEST_REL: _manifest_bytes(agents, out)}
    lines: list[str] = []
    for rel, data in sorted(expected.items()):
        target = root / rel
        if not target.is_file():
            lines.append(f"{rel}: missing")
        elif agents.lf_sha256(target.read_bytes()) != agents.lf_sha256(data):
            lines.append(f"{rel}: stale")
    lines += [
        f"{rel}: extra" for rel in sorted(set(_manifest(root)) - set(out)) if (root / rel).is_file()
    ]
    return len(out), sorted(lines)


def write(root: Path) -> dict[str, int]:
    """Build, write what changed, remove what's no longer produced, and record the manifest."""
    agents = _load_agents()
    out = build(root)
    old = _manifest(root)
    written = removed = 0
    for rel, data in out.items():
        target = root / rel
        if not target.is_file() or target.read_bytes() != data:
            _write_bytes(target, data)
            written += 1
    for rel in sorted(set(old) - set(out)):
        target = root / rel
        if not target.is_file():
            continue
        if rel in SHARED:  # a repo's own config: take out only the factory's entry
            try:
                left = _merged(_load_json(root, rel), rel, None)
            except BuildError:
                continue  # unreadable now: leave the repo's file alone
            if set(left) - {"version"}:
                _write_bytes(target, _json(left))
                written += 1
                continue
        target.unlink()
        removed += 1
        _prune(root, target)
    _write_bytes(root / MANIFEST_REL, _manifest_bytes(agents, out))
    return {"files": len(out), "written": written, "removed": removed}


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="build.py", description=__doc__.split("\n")[0])
    parser.add_argument(
        "--root", help="repository root (default: the nearest folder holding .agentic/)"
    )
    parser.add_argument(
        "--check", action="store_true", help="write nothing; exit 1 if any file is out of step"
    )
    args = parser.parse_args(argv)
    try:
        agents = _load_agents()
        root = Path(args.root).resolve() if args.root else agents.state.find_root(Path.cwd())
        if args.check:
            files, drift = check(root)
        else:
            counts = write(root)
    except BuildError as exc:
        print(f"build.py: {exc}", file=sys.stderr)
        return 2
    if args.check:
        for line in drift:
            print(line)
        if drift:
            shown = "file" if len(drift) == 1 else "files"
            print(f"{len(drift)} {shown} out of step; run python .factory/adapters/build.py")
            return 1
        print(f"{files} tool files current")
        return 0
    print(
        f"built {counts['files']} files: {counts['written']} written, {counts['removed']} removed"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
